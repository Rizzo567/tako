import type {Change,Conversation,Family,Mods,Pick,Turn} from './types.js'

type In=string|Turn
const T=(s:string):Turn=>({text:s}),Q=(s:string):Turn=>({text:s,q:true}),V=(s:string):Turn=>({voice:s}),VQ=(s:string):Turn=>({voice:s,q:true}),W=(m:number):Turn=>({wait:m})
